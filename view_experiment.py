EXP_DIR = Path("exp")


def scan_experiments(exp_dir: Path) -> List[Dict[str, Any]]:
    """
    Scan exp/ directory for all experiment results

    Returns:
        List of experiment metadata dictionaries
    """
    experiments = []

    # Find all results.json files
    for results_file in exp_dir.rglob("results.json"):
        try:
            with open(results_file, 'r', encoding='utf-8') as f:
                data = json.load(f)

            # Extract metadata
            exp_metadata = data.get('experiment_metadata', {})
            summary = data.get('summary', {})
            results = data.get('results', [])

            # Build results map (unique_id -> {is_correct, success})
            results_map = {}
            for result in results:
                unique_id = result.get('unique_id')
                is_correct = result.get('is_correct', False)
                success = result.get('success', True)  # Default to True if not specified
                if unique_id:
                    results_map[unique_id] = {
                        'is_correct': is_correct,
                        'success': success
                    }

            # Construct relative path from exp/
            rel_path = results_file.relative_to(exp_dir)

            experiments.append({
                'path': str(rel_path),
                'full_path': str(results_file),
                'name': exp_metadata.get('experiment_name', rel_path.parent.name),
                'date': exp_metadata.get('experiment_date', 'N/A'),
                'dataset': exp_metadata.get('dataset', 'N/A'),
                'model': exp_metadata.get('model_type', 'N/A'),
                'flow': exp_metadata.get('flow', 'N/A'),
                'flow_config': exp_metadata.get('flow_config', []),
                'total': summary.get('total_questions', 0),
                'correct': summary.get('correct', 0),
                'accuracy': summary.get('accuracy', 0.0),
                'successful': summary.get('successful') or summary.get('grading_successful', 0),
                'failed': summary.get('failed', 0),
                'results_map': results_map  # Add results map for conditional probability
            })
        except Exception as e:
            print(f"Error loading {results_file}: {e}")
            continue

    # Sort by date (newest first)
    experiments.sort(key=lambda x: x['date'], reverse=True)

    return experiments


def load_experiment_details(exp_path: str) -> Dict[str, Any]:
    """Load full experiment details including results"""
    try:
        with open(exp_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception as e:
        return {'error': str(e)}


