#!/usr/bin/env python3
"""
Baseline Results Evaluation Script

This script evaluates baseline results generated by generate_baseline.py
by grading the generated answers against ground truth.

=============================================================================
USAGE
=============================================================================

Basic syntax:
    python run_eval_baseline.py --results_path <path_to_baseline_results>

Examples:
    # Evaluate CodeElo baseline (C++ code execution)
    python run_eval_baseline.py --results_path data/CodeElo/gpt-oss/p1/results.json

    # Evaluate AIME2025 baseline (LLM grading)
    python run_eval_baseline.py --results_path data/AIME2025__R10/gpt-oss/p1/results.json

    # Evaluate GPQA-Diamond baseline (exact match grading)
    python run_eval_baseline.py --results_path data/GPQA-Diamond/gpt-oss/p1/results.json

    # Limit processing for testing
    python run_eval_baseline.py --results_path data/AIME2025__R10/gpt-oss/p1/results.json --limit 5

=============================================================================
Parameters
=============================================================================

--results_path: Path to baseline results.json (required)
--output_path: Path to save evaluated results (default: overwrite input file)
--mode: LLM client mode for grading ('openrouter' or 'local', default: 'openrouter')
--limit: Limit number of questions to evaluate (for testing)
--max_workers: Maximum concurrent workers (default: 16 for generation, 64 for grading)
--judge_model: Model type for LLM grading (default: 'gpt-oss')

=============================================================================
"""

import json
import argparse
from pathlib import Path
from typing import List, Dict
from tqdm import tqdm
import logging

from llm_client import LLMClient, Task, Request
from logger_config import setup_logger
from core import (
    parse_yes_no_response,
    GRADING_PROMPT,
    extract_code_blocks,
    compile_and_execute_cpp,
    normalize_output,
    append_to_jsonl,
    load_from_jsonl
)

# Setup logger
logger = setup_logger(__name__, log_file='logs/run_eval_baseline.log')

# Concurrency settings
DEFAULT_MAX_WORKERS = 16
GRADED_MAX_WORKERS = 64


def detect_dataset_type(results: List[Dict]) -> str:
    """
    自動檢測數據集類型

    採樣檢查多個結果以確定數據集類型，基於 unique_id 和數據結構。

    Args:
        results: 結果列表

    Returns:
        'code'、'science' 或 'math'（預設）
    """
    if not results:
        return 'math'

    # 定義數據集類型的檢測模式
    dataset_patterns = {
        'code': ['codeforces', 'codeeml', 'arc', 'codeelo'],
        'science': ['gpqa', 'gsm8k'],
        'math': ['aime', 'math500', 'mathdialogue']
    }

    # 採樣多個結果以驗證一致性
    sample_size = min(3, len(results))
    detected_types = []

    for i in range(sample_size):
        result = results[i]
        unique_id = result.get('unique_id', '').lower()

        # 檢查 unique_id 中的模式
        detected_type = None
        for dataset_type, patterns in dataset_patterns.items():
            if any(pattern.lower() in unique_id for pattern in patterns):
                detected_type = dataset_type
                break

        # 如果無法從 unique_id 確定，檢查數據結構
        if detected_type is None:
            # Code datasets 有 test_cases
            if 'test_cases' in result:
                detected_type = 'code'
            # Science datasets 可能有單字母答案
            elif result.get('answer', '').strip().upper() in ['A', 'B', 'C', 'D']:
                detected_type = 'science'
            else:
                detected_type = 'math'

        detected_types.append(detected_type)

    # 如果多個樣本類型一致，使用該類型
    if detected_types:
        first_type = detected_types[0]
        if all(t == first_type for t in detected_types):
            return first_type
        else:
            logger.debug(
                f"Mixed dataset types detected: {detected_types}. "
                f"Using first: {first_type}"
            )
            return first_type

    return 'math'


def prepare_evaluation_items(results: List[Dict]) -> List[Dict]:
    """
    準備評分項目，從 baseline 格式轉換為評分格式

    Baseline 格式:
    - Code: {unique_id, question, test_cases, result: {traj, answer, ...}}
    - Math: {unique_id, question, answer (ground_truth), result: {traj, answer, ...}}

    評分格式 (類似 experiment):
    - {unique_id, question_id, question, ground_truth, generated_answer, ...}

    Args:
        results: Baseline 結果列表

    Returns:
        評分項目列表
    """
    eval_items = []

    for i, result in enumerate(results):
        # 提取基本信息
        unique_id = result.get('unique_id', f'item-{i}')
        question = result.get('question', '')

        # 提取 ground_truth (兩種格式)
        # Code: test_cases (list)
        # Math: answer (string/number)
        ground_truth = result.get('test_cases') or result.get('answer', '')

        # 提取 generated_answer
        # 從 result.answer 獲取
        generated_answer = result.get('result', {}).get('answer', '')

        # 構建評分項目
        eval_item = {
            'unique_id': unique_id,
            'question_id': i,
            'question': question,
            'ground_truth': ground_truth,
            'generated_answer': generated_answer,
            'original_reasoning': result.get('result', {}).get('traj', ''),
            # 評分字段（初始為空）
            'is_correct': None,
            'grading_reasoning': None,
            'success': False,
            'error': None
        }

        # 保留 test_cases (code datasets)
        if 'test_cases' in result:
            eval_item['test_cases'] = result['test_cases']

        eval_items.append(eval_item)

    return eval_items


def create_code_grading_tasks(eval_items: List[Dict]) -> List[Dict]:
    """
    創建代碼本地執行任務

    Args:
        eval_items: 評分項目列表

    Returns:
        本地執行任務列表
    """
    tasks = []

    for item in eval_items:
        # 提取代碼
        answer_text = item['generated_answer']
        code_blocks = extract_code_blocks(answer_text)

        # 優先選擇 C++ 代碼塊
        cpp_blocks = [block for block in code_blocks if block[0].lower() in ['cpp', 'c++', 'c']]
        if cpp_blocks:
            code = cpp_blocks[0][1]
        elif code_blocks:
            code = code_blocks[0][1]
        else:
            code = ""

        # 獲取測試用例
        test_cases = item.get('test_cases', [])

        tasks.append({
            'type': 'code_execution',
            'unique_id': item['unique_id'],
            'question_id': item['question_id'],
            'code': code,
            'test_cases': test_cases,
            'item': item
        })

    return tasks


def create_math_grading_tasks(eval_items: List[Dict], judge_model_type: str = 'gpt-oss') -> List[Task]:
    """
    創建數學答案 LLM 評分任務

    Args:
        eval_items: 評分項目列表
        judge_model_type: 判官模型類型

    Returns:
        LLM 評分任務列表
    """
    tasks = []

    for item in eval_items:
        tasks.append(Task(
            index=item['question_id'],
            request=Request(
                queries=[GRADING_PROMPT.format(
                    problem=item['question'],
                    ground_truth=item['ground_truth'],
                    model_answer=item['generated_answer']
                )],
                model_type=judge_model_type,
                system_prompt="You are a helpful mathematical grading assistant.",
                reasoning_on=False,
                temperature=0.01
            ),
            metadata={'unique_id': item['unique_id']}
        ))

    return tasks


def evaluate_baseline(
    results_path: str,
    output_path: str = None,
    mode: str = 'openrouter',
    limit: int = None,
    max_workers: int = DEFAULT_MAX_WORKERS,
    judge_model: str = 'gpt-oss'
):
    """
    評分 baseline 結果

    Args:
        results_path: Baseline results.json 路徑
        output_path: 輸出路徑（默認覆蓋輸入文件）
        mode: LLM client 模式
        limit: 限制評分數量
        max_workers: 最大並發數
        judge_model: 判官模型類型
    """
    # 設置輸出路徑
    if output_path is None:
        output_path = results_path

    output_path = Path(output_path)

    # 設置 JSONL 緩存路徑
    grading_jsonl = output_path.parent / f"{output_path.stem}_grading.jsonl"

    print(f"Loading baseline results from {results_path}")

    # 讀取 baseline 結果
    with open(results_path, 'r', encoding='utf-8') as f:
        baseline_results = json.load(f)

    # 確保是列表格式
    if isinstance(baseline_results, dict):
        # 如果是 experiment 格式，提取 results
        baseline_results = baseline_results.get('results', [])

    if limit:
        baseline_results = baseline_results[:limit]
        print(f"Limited to {limit} questions")

    print(f"Total items: {len(baseline_results)}")

    # 檢測數據集類型
    dataset_type = detect_dataset_type(baseline_results)
    print(f"Dataset type: {dataset_type}")

    # 準備評分項目
    print("Preparing evaluation items...")
    eval_items = prepare_evaluation_items(baseline_results)

    # 載入已評分結果（支持 resume）
    existing_graded = load_from_jsonl(grading_jsonl)
    graded_map = {item['unique_id']: item for item in existing_graded if item.get('success', False)}

    # 過濾出需要評分的項目
    need_grading = [item for item in eval_items if item['unique_id'] not in graded_map]

    print(f"Already graded: {len(graded_map)}")
    print(f"Need to grade: {len(need_grading)}")

    # 創建評分任務
    if dataset_type == 'code':
        # Code 評分：本地 C++ 執行
        print(f"\n=== Grading C++ code for {len(need_grading)} items ===")

        grading_tasks = create_code_grading_tasks(need_grading)

        for task in tqdm(grading_tasks, desc="Executing C++"):
            code = task['code']
            test_cases = task['test_cases']

            # 執行所有測試用例
            all_passed = True
            execution_details = []

            for test_input, expected_output in test_cases:
                exec_result = compile_and_execute_cpp(
                    code=code,
                    test_input=test_input,
                    timeout=2
                )

                # 檢查狀態和輸出
                if exec_result['status'] != 'AC':
                    all_passed = False
                elif normalize_output(exec_result['output']) != normalize_output(expected_output):
                    all_passed = False
                    exec_result['status'] = 'WA'

                execution_details.append({
                    'input': test_input[:50],
                    'expected': expected_output[:50],
                    'actual': exec_result['output'][:50],
                    'status': exec_result['status']
                })

            # 更新結果
            graded_item = task['item'].copy()
            graded_item['is_correct'] = all_passed
            graded_item['grading_reasoning'] = json.dumps(execution_details, indent=2)
            graded_item['grading_status'] = 'AC' if all_passed else execution_details[0]['status']
            graded_item['success'] = True

            # 更新 map
            graded_map[graded_item['unique_id']] = graded_item

            # 保存到 JSONL
            append_to_jsonl(grading_jsonl, graded_item)

    else:
        # Math/Science 評分：使用 LLM
        print(f"\n=== Grading {len(need_grading)} answers with LLM (judge: {judge_model}) ===")

        if len(need_grading) == 0:
            print("All items already graded, skipping")
        else:
            # 初始化 LLM client
            client = LLMClient(mode=mode, timeout=60)

            grading_tasks = create_math_grading_tasks(need_grading, judge_model_type=judge_model)

            for grading_task in tqdm(
                client.generate_concurrent(grading_tasks, max_workers=GRADED_MAX_WORKERS),
                total=len(grading_tasks)
            ):
                if not grading_task.response.success:
                    logger.error(f"Grading failed for {grading_task.metadata['unique_id']}: {grading_task.response.err_message}")
                    continue

                unique_id = grading_task.metadata['unique_id']

                # 找到對應的評分項目
                item = next((item for item in need_grading if item['unique_id'] == unique_id), None)
                if not item:
                    continue

                # 更新評分信息
                graded_item = item.copy()
                graded_item['is_correct'] = parse_yes_no_response(grading_task.response.content)
                graded_item['grading_reasoning'] = grading_task.response.content
                graded_item['success'] = True

                # 更新 map
                graded_map[unique_id] = graded_item

                # 保存到 JSONL
                append_to_jsonl(grading_jsonl, graded_item)

    # 重建最終結果
    print("\n=== Building final results ===")

    # 合併評分結果回原始結果
    final_results = []
    for orig_result in baseline_results:
        unique_id = orig_result.get('unique_id', '')

        # 獲取評分結果
        graded = graded_map.get(unique_id, {})

        # 合併
        final_result = orig_result.copy()
        final_result['is_correct'] = graded.get('is_correct')
        final_result['grading_reasoning'] = graded.get('grading_reasoning')
        final_result['success'] = graded.get('success', False)

        if 'grading_status' in graded:
            final_result['grading_status'] = graded['grading_status']

        final_results.append(final_result)

    # 計算統計
    total = len(final_results)
    graded_count = sum(1 for r in final_results if r.get('success', False))
    correct_count = sum(1 for r in final_results if r.get('is_correct', False))
    accuracy = correct_count / graded_count if graded_count > 0 else 0.0

    # 保存結果
    print(f"Saving results to {output_path}")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(final_results, f, indent=2, ensure_ascii=False)

    # 打印統計
    print("\n" + "="*60)
    print("EVALUATION RESULTS")
    print("="*60)
    print(f"Total items:           {total}")
    print(f"Successfully graded:   {graded_count}")
    print(f"Correct answers:       {correct_count}")
    print(f"Accuracy:              {accuracy:.2%}")
    print("="*60)
    print(f"\nGrading JSONL: {grading_jsonl}")
    print(f"Final results: {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description='Evaluate baseline results by grading generated answers'
    )
    parser.add_argument(
        '--results_path',
        type=str,
        required=True,
        help='Path to baseline results.json'
    )
    parser.add_argument(
        '--output_path',
        type=str,
        default=None,
        help='Path to save evaluated results (default: overwrite input file)'
    )
    parser.add_argument(
        '--mode',
        type=str,
        default='openrouter',
        choices=['openrouter', 'local'],
        help='LLM client mode for grading'
    )
    parser.add_argument(
        '--limit',
        type=int,
        default=None,
        help='Limit number of items to evaluate (for testing)'
    )
    parser.add_argument(
        '--max_workers',
        type=int,
        default=DEFAULT_MAX_WORKERS,
        help=f'Maximum number of concurrent workers (default: {DEFAULT_MAX_WORKERS})'
    )
    parser.add_argument(
        '--judge_model',
        type=str,
        default='gpt-oss',
        help='Model type for LLM grading (default: gpt-oss)'
    )

    args = parser.parse_args()

    # 運行評分
    evaluate_baseline(
        results_path=args.results_path,
        output_path=args.output_path,
        mode=args.mode,
        limit=args.limit,
        max_workers=args.max_workers,
        judge_model=args.judge_model
    )


if __name__ == '__main__':
    main()
