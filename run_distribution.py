def load_and_validate_input(args):
    """
    Load and validate input data from results.json

    Returns:
        Tuple of (results, experiment_metadata, model_type, output_paths)
        where output_paths is (sampling_jsonl, output_json)
    """
    print(f"\nLoading results from {args.result}...")
    with open(args.result, 'r', encoding='utf-8') as f:
        input_data = json.load(f)

    results = input_data.get('results', [])
    experiment_metadata = input_data.get('experiment_metadata', {})

    # Extract model_type from metadata
    model_type = experiment_metadata.get('model_type', 'gpt-oss')
    print(f"Detected model type: {model_type}")

    if args.limit:
        results = results[:args.limit]
        print(f"Limited to {args.limit} questions")

    print(f"Total questions: {len(results)}")

    # Prepare output paths (JSONL strategy)
    output_path = Path(args.out)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    sampling_jsonl = output_path.parent / f"{output_path.stem}_sampling.jsonl"
    output_json = output_path

    print(f"Sampling JSONL: {sampling_jsonl}")
    print(f"Final JSON:     {output_json}")

    # Load existing sampling results
    existing_sampling = load_from_jsonl(sampling_jsonl)
    completed_unique_ids = {r['unique_id'] for r in existing_sampling}

    print(f"Found {len(existing_sampling)} existing sampling results")
    print(f"Completed unique IDs: {len(completed_unique_ids)}")

    # Filter out completed questions (use unique_id to handle repetitions)
    results_to_process = [r for r in results if r['unique_id'] not in completed_unique_ids]
    print(f"Questions to process: {len(results_to_process)}")

    return results_to_process, experiment_metadata, model_type, (sampling_jsonl, output_json)


def build_sampling_tasks(results_to_process, args, model_type):
    """
    Build all sampling tasks (questions × n samples)

    Returns:
        Tuple of (all_tasks, question_metadata)
    """
    print(f"\n=== Building all tasks (questions × n samples) ===")
    all_tasks = []
    question_metadata = {}  # Map unique_id to metadata

    for result_item in results_to_process:
        question_id = result_item['question_id']
        unique_id = result_item['unique_id']
        question = result_item['question']
        ground_truth = result_item['ground_truth']
        processed_reasoning = result_item['processed_reasoning']

        # Store question metadata (use unique_id as key to handle repetitions)
        question_metadata[unique_id] = {
            'question_id': question_id,
            'unique_id': unique_id,
            'question': question,
            'ground_truth': ground_truth,
            'processed_reasoning': processed_reasoning
        }

        # Create n tasks for this question using the helper function
        for sample_id in range(args.n):
            task = build_sampling_request(
                question=question,
                processed_reasoning=processed_reasoning,
                answer_free_gen=args.answer_free_gen,
                model_type=model_type,
                temperature=args.temperature,
                task_index=len(all_tasks),  # Global task index
                metadata={
                    'unique_id': unique_id,
                    'sample_id': sample_id
                }
            )
            all_tasks.append(task)

    total_tasks = len(all_tasks)
    print(f"Total tasks to process: {total_tasks} ({len(results_to_process)} questions × {args.n} samples)")
    print(f"Max workers: {args.max_workers}")

    return all_tasks, question_metadata


def execute_and_group_tasks(all_tasks, client, args, question_metadata, sampling_jsonl):
    """
    Execute all tasks in parallel with immediate JSONL writing

    When all N samples for a question are completed, immediately calculates
    distribution and writes to JSONL (thread-safe).

    Args:
        all_tasks: List of all tasks to execute
        client: LLM client instance
        args: Command line arguments (n, answer_free_gen, max_workers)
        question_metadata: Dict mapping unique_id to question metadata
        sampling_jsonl: Path to JSONL file for immediate saving

    Returns:
        None (results are written to JSONL immediately)
    """
    import threading
    from collections import defaultdict

    print(f"\n=== Executing all tasks with immediate JSONL writing ===")

    # Thread-safe tracking
    lock = threading.Lock()
    samples_by_question = defaultdict(list)
    completed_count = defaultdict(int)
    saved_questions = set()  # Track which questions have been saved

    with tqdm(total=len(all_tasks), desc="Sampling") as pbar:
        for completed_task in client.complete_concurrent(all_tasks, max_workers=args.max_workers):
            unique_id = completed_task.metadata['unique_id']

            # Process task response
            sample = process_completed_task(completed_task, args.answer_free_gen)

            # Thread-safe update and check for completion
            with lock:
                samples_by_question[unique_id].append(sample)
                completed_count[unique_id] += 1

                # Check if all samples for this question are completed
                if completed_count[unique_id] == args.n and unique_id not in saved_questions:
                    # Mark as saved to prevent duplicate writes
                    saved_questions.add(unique_id)

                    # Get metadata
                    meta = question_metadata[unique_id]
                    samples = samples_by_question[unique_id]

                    # Sort samples by sample_id
                    samples.sort(key=lambda x: x['sample_id'])

                    # Calculate distribution
                    distribution = calculate_distribution(samples, meta['ground_truth'])

                    # Calculate summary stats
                    total_valid_samples = sum(1 for s in samples if s.get('success') and s.get('extracted_answer'))
                    total_invalid_samples = len(samples) - total_valid_samples

                    # Build result
                    sampling_result = {
                        'unique_id': meta['unique_id'],
                        'question_id': meta['question_id'],
                        'question': meta['question'],
                        'ground_truth': meta['ground_truth'],
                        'processed_reasoning': meta['processed_reasoning'],
                        'samples': samples,
                        'distribution': distribution,
                        'total_samples': len(samples),
                        'total_valid_samples': total_valid_samples,
                        'total_invalid_samples': total_invalid_samples,
                    }

                    # Append to JSONL immediately (thread-safe with lock)
                    append_to_jsonl(sampling_jsonl, sampling_result)

            # Update progress bar
            pbar.update(1)

    print(f"\n=== All tasks completed, {len(saved_questions)} questions saved to JSONL ===")


def generate_final_output(sampling_jsonl, output_json, args, experiment_metadata, model_type):
    """
    Generate final output JSON from JSONL results
    """
    print(f"\n=== Building final output ===")

    # Reload all sampling results (to ensure we have everything)
    all_sampling_results = load_from_jsonl(sampling_jsonl)

    # Sort by question_id
    all_sampling_results.sort(key=lambda x: x['question_id'])

    # Calculate summary statistics
    total_questions = len(all_sampling_results)
    avg_top1_accuracy = sum(
        r['distribution'][0]['is_correct'] if r['distribution'] else False
        for r in all_sampling_results
    ) / total_questions if total_questions > 0 else 0

    # Calculate average entropy (Shannon entropy of distribution)
    avg_entropy = sum(
        calculate_entropy(r['distribution'])
        for r in all_sampling_results
    ) / total_questions if total_questions > 0 else 0

    summary = {
        'total_questions': total_questions,
        'avg_top1_accuracy': avg_top1_accuracy,
        'avg_entropy': avg_entropy,
        'n_samples': args.n,
        'answer_free_gen': args.answer_free_gen,
        'temperature': args.temperature
    }

    # Build metadata
    output_metadata = {
        'source_result': args.result,
        'n_samples': args.n,
        'answer_free_gen': args.answer_free_gen,
        'model': model_type,
        'temperature': args.temperature,
        'timestamp': datetime.now().isoformat(),
        'source_experiment_metadata': experiment_metadata
    }

    # Final output structure
    final_output = {
        'metadata': output_metadata,
        'summary': summary,
        'results': all_sampling_results
    }

    # Save final JSON
    with open(output_json, 'w', encoding='utf-8') as f:
        json.dump(final_output, f, indent=2, ensure_ascii=False)

    print(f"\n{'='*60}")
    print(f"DISTRIBUTION ANALYSIS COMPLETE")
    print(f"{'='*60}")
    print(f"Total questions:        {summary['total_questions']}")
    print(f"Samples per question:   {args.n}")
    print(f"Avg top-1 accuracy:     {summary['avg_top1_accuracy']:.2%}")
    print(f"Avg entropy:            {summary['avg_entropy']:.4f}")
    print(f"{'='*60}")
    print(f"\nSampling JSONL: {sampling_jsonl}")
    print(f"Final JSON:     {output_json}")


