# =============================================================================
# Answer Extraction
# =============================================================================

def extract_answer_from_completion(completion: str) -> Optional[str]:
    """
    Extract answer from completion text using numeric pattern [0-9]+.

    Takes the last occurrence if multiple numeric matches exist.

    Args:
        completion: Generated text from LLM

    Returns:
        Extracted answer string (numeric), or None if no number found

    Examples:
        >>> extract_answer_from_completion("The answer is 42")
        '42'
        >>> extract_answer_from_completion("First 10 then 20")
        '20'
        >>> extract_answer_from_completion("No answer here")
        None
        >>> extract_answer_from_completion("The result: 123")
        '123'
    """
    # Pattern matches one or more digits
    pattern = r'[0-9]+'

    matches = re.findall(pattern, completion)

    if not matches:
        return None

    # Take the last match
    answer = matches[-1].strip()

    # Return None if empty
    if not answer:
        return None

    return answer


# =============================================================================
# Answer Normalization
# =============================================================================

def normalize_answer(answer: str) -> Optional[str]:
    """
    Normalize mathematical answer using sympy for equivalence checking.

    Converts mathematical expressions to canonical form so that equivalent
    answers (e.g., "1/2" and "2/4") map to the same normalized form.

    Args:
        answer: Raw answer string

    Returns:
        Normalized answer string, or original if normalization fails

    Examples:
        >>> normalize_answer("2/4")
        '1/2'
        >>> normalize_answer("42.0")
        '42'
        >>> normalize_answer("not a number")
        'not a number'
    """
    import sympy as sp

    if not answer:
        return None

    # Strip whitespace
    answer = answer.strip()

    try:
        # Try to parse as sympy expression
        # Handle LaTeX fractions
        answer_processed = answer.replace('\\frac', 'Rational')
        answer_processed = re.sub(r'Rational\{(\d+)\}\{(\d+)\}', r'Rational(\1, \2)', answer_processed)

        expr = sp.sympify(answer_processed)

        # Simplify and convert to string
        simplified = sp.simplify(expr)

        # Convert floats to integers if they are whole numbers
        if simplified.is_Float:
            if simplified % 1 == 0:
                normalized = str(int(simplified))
            else:
                normalized = str(simplified)
        else:
            normalized = str(simplified)

        return normalized

    except (sp.SympifyError, ValueError, TypeError, AttributeError) as e:
        # If parsing fails, return original string
        logger.debug(f"Failed to normalize '{answer}': {e}")
        return answer


# =============================================================================
# Entropy Calculation
# =============================================================================

def calculate_entropy(distribution: List[Dict]) -> float:
    """
    Calculate Shannon entropy of an answer distribution.

    Entropy measures the uncertainty/randomness in the distribution.
    Higher entropy means more diverse answers, lower entropy means
    more concentrated on a single answer.

    Args:
        distribution: List of distribution entries with 'percentage' field

    Returns:
        Shannon entropy value (in bits). Returns 0 for empty distribution.

    Examples:
        >>> # Uniform distribution: maximum entropy
        >>> dist = [
        ...     {'answer': 'A', 'percentage': 0.5},
        ...     {'answer': 'B', 'percentage': 0.5}
        ... ]
        >>> entropy = calculate_entropy(dist)
        >>> abs(entropy - 1.0) < 0.01  # Should be 1.0
        True

        >>> # Single answer: minimum entropy (0)
        >>> dist = [{'answer': 'A', 'percentage': 1.0}]
        >>> calculate_entropy(dist)
        0.0

        >>> # Empty distribution
        >>> calculate_entropy([])
        0
    """
    import math

    if not distribution:
        return 0

    return -sum(
        d['percentage'] * math.log2(d['percentage'])
        for d in distribution
        if d['percentage'] > 0
    )


