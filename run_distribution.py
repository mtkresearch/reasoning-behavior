# Distribution Calculation
# =============================================================================

def calculate_distribution(
    samples: List[Dict],
    correct_answer: str
) -> List[Dict]:
    """
    Calculate answer distribution from samples.

    Groups samples by normalized answer, counts occurrences, and ranks by frequency.

    Args:
        samples: List of sample dicts with 'extracted_answer' key
        correct_answer: Ground truth answer for correctness checking

    Returns:
        List of distribution entries sorted by count (descending), each containing:
        - answer: The answer value
        - count: Number of occurrences
        - percentage: Proportion of valid samples
        - is_correct: Whether this matches the ground truth
        - rank: Ranking by frequency (1 = most frequent)

    Examples:
        >>> samples = [
        ...     {"extracted_answer": "42"},
        ...     {"extracted_answer": "42"},
        ...     {"extracted_answer": "43"},
        ... ]
        >>> dist = calculate_distribution(samples, "42")
        >>> len(dist)
        2
        >>> dist[0]['count']
        2
    """
    from collections import Counter

    # Extract and normalize answers, filtering out None
    normalized_answers = []
    raw_to_normalized = {}  # Map to track original answer for each normalized form

    for sample in samples:
        raw_answer = sample.get('extracted_answer')
        if raw_answer is None:
            continue

        normalized = normalize_answer(raw_answer)
        if normalized:
            normalized_answers.append(normalized)
            # Keep first occurrence of raw answer for display
            if normalized not in raw_to_normalized:
                raw_to_normalized[normalized] = raw_answer

    # Count occurrences
    counter = Counter(normalized_answers)

    if not counter:
        return []

    # Normalize correct answer for comparison
    normalized_correct = normalize_answer(correct_answer)

    # Calculate total valid samples
    total_valid = sum(counter.values())

    # Build distribution entries with dense ranking
    # Dense ranking: same count gets same rank, ranks are consecutive (1, 2, 2, 3)
    distribution = []
    current_rank = 1
    prev_count = None

    for normalized_answer, count in counter.most_common():
        # Dense ranking: same count gets same rank
        if prev_count is not None and count != prev_count:
            current_rank += 1

        distribution.append({
            'answer': raw_to_normalized[normalized_answer],  # Use original form for display
            'normalized_answer': normalized_answer,
            'count': count,
            'percentage': count / total_valid if total_valid > 0 else 0,
            'is_correct': normalized_answer == normalized_correct,
            'rank': current_rank
        })

        prev_count = count

    return distribution


