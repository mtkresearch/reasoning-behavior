def calculate_distribution_stats(results: List[Dict]) -> Dict[str, Optional[float]]:
    """
    Calculate comprehensive statistics from distribution results.

    Computes:
    - avg_entropy: Average Shannon entropy across all questions
    - avg_answer_prob: Average probability of correct answer
    - mean_rank: Average rank of correct answer
    - std_rank: Standard deviation of correct answer ranks
    - top1_accuracy: Proportion of questions where correct answer is at rank 1

    Args:
        results: List of result dicts, each containing a 'distribution' field

    Returns:
        Dictionary with keys: avg_entropy, avg_answer_prob, mean_rank, std_rank, top1_accuracy
        Values are None if no valid data available

    Examples:
        >>> results = [
        ...     {
        ...         "distribution": [
        ...             {"answer": "42", "percentage": 0.6, "is_correct": True, "rank": 1},
        ...             {"answer": "43", "percentage": 0.4, "is_correct": False, "rank": 2},
        ...         ]
        ...     },
        ... ]
        >>> stats = calculate_distribution_stats(results)
        >>> stats['avg_answer_prob']
        0.6
        >>> stats['top1_accuracy']
        1.0
    """
    entropies = []
    answer_probs = []
    correct_ranks = []
    top1_correct_count = 0

    for result in results:
        distribution = result.get('distribution', [])

        # Skip empty distributions
        if not distribution:
            continue

        # Calculate entropy for this question
        entropy = calculate_entropy(distribution)
        entropies.append(entropy)

        # Find correct answer probability and rank
        correct_prob = 0.0
        correct_rank = None
        max_rank = 0

        for entry in distribution:
            rank = entry.get('rank', 0)
            max_rank = max(max_rank, rank)

            if entry.get('is_correct', False):
                correct_prob = entry.get('percentage', 0.0)
                correct_rank = rank
                break

        # If correct answer not in distribution, use prob=0 and max_rank+1
        answer_probs.append(correct_prob)
        if correct_rank is None:
            correct_rank = max_rank + 1
        correct_ranks.append(correct_rank)

        # Count if correct answer is at rank 1
        if correct_rank == 1:
            top1_correct_count += 1

    # Calculate averages
    avg_entropy = sum(entropies) / len(entropies) if entropies else None
    avg_answer_prob = sum(answer_probs) / len(answer_probs) if answer_probs else None

    # Calculate rank statistics
    if correct_ranks:
        mean_rank = sum(correct_ranks) / len(correct_ranks)
        if len(correct_ranks) == 1:
            std_rank = 0.0
        else:
            import math
            variance = sum((r - mean_rank) ** 2 for r in correct_ranks) / len(correct_ranks)
            std_rank = math.sqrt(variance)

        # Calculate top-1 accuracy
        top1_accuracy = top1_correct_count / len(correct_ranks)
    else:
        mean_rank = None
        std_rank = None
        top1_accuracy = None

    return {
        'avg_entropy': avg_entropy,
        'avg_answer_prob': avg_answer_prob,
        'mean_rank': mean_rank,
        'std_rank': std_rank,
        'top1_accuracy': top1_accuracy
    }


