def build_sampling_request(
    question: str,
    processed_reasoning: str,
    answer_free_gen: bool,
    model_type: str,
    temperature: float,
    task_index: int,
    metadata: Optional[Dict] = None
) -> Task:
    """
    Build a sampling request Task for generating answer completions.

    Args:
        question: The question text
        processed_reasoning: Processed reasoning chain to use as prompt
        answer_free_gen: Whether to use answer-free generation (no prefill)
        model_type: Model type to use
        temperature: Sampling temperature
        task_index: Unique index for this task
        metadata: Optional metadata to attach to the task

    Returns:
        Task object ready for execution

    Examples:
        >>> task = build_sampling_request(
        ...     question="What is 2+2?",
        ...     processed_reasoning="Let's think step by step...",
        ...     answer_free_gen=False,
        ...     model_type="gpt-oss",
        ...     temperature=0.5,
        ...     task_index=0
        ... )
        >>> task.request.model_type
        'gpt-oss'
    """
    if answer_free_gen:
        # Answer-free generation: continue from reasoning
        prompt = build_gpt_oss_prompt_with_reasoning(question, processed_reasoning)
        max_tokens = 3000
    else:
        # With answer prefill: "Thus, the answer is"
        prompt = build_gpt_oss_prompt_with_reasoning_prefilled_answer(
            question,
            processed_reasoning,
            prefill_text=PREFILL_TEXT
        )
        max_tokens = 20

    request = CompletionRequest(
        prompt=prompt,
        model_type=model_type,
        temperature=temperature,
        max_tokens=max_tokens
    )

    task = Task(
        index=task_index,
        request=request,
        metadata=metadata or {}
    )

    return task


