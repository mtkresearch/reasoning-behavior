# Answer Rank Statistics
# =============================================================================

def calculate_answer_rank_stats(results: List[Dict]) -> Tuple[Optional[float], Optional[float]]:
    """
    Calculate statistics of correct answer ranks across all questions.

    For each question, finds the rank of the correct answer in the distribution.
    If correct answer is not in distribution, uses max_rank + 1.

    Args:
        results: List of result dicts, each containing a 'distribution' field

    Returns:
        Tuple of (mean_rank, std_rank):
        - mean_rank: Average rank of correct answers
        - std_rank: Standard deviation of correct answer ranks
        Returns (None, None) if no valid ranks found

    Examples:
        >>> results = [
        ...     {
        ...         "distribution": [
        ...             {"answer": "42", "is_correct": True, "rank": 1},
        ...             {"answer": "43", "is_correct": False, "rank": 2},
        ...         ]
        ...     },
        ...     {
        ...         "distribution": [
        ...             {"answer": "100", "is_correct": False, "rank": 1},
        ...             {"answer": "150", "is_correct": True, "rank": 2},
        ...         ]
        ...     },
        ... ]
        >>> mean, std = calculate_answer_rank_stats(results)
        >>> mean
        1.5
        >>> std
        0.5
    """
    import math

    correct_answer_ranks = []

    for result in results:
        distribution = result.get('distribution', [])

        # Skip empty distributions
        if not distribution:
            continue

        # Find correct answer rank
        correct_rank = None
        max_rank = 0

        for entry in distribution:
            rank = entry.get('rank', 0)
            max_rank = max(max_rank, rank)

            if entry.get('is_correct', False):
                correct_rank = rank
                break

        # If correct answer not found, use max_rank + 1
        if correct_rank is None:
            correct_rank = max_rank + 1

        correct_answer_ranks.append(correct_rank)

    # Return None if no valid ranks
    if not correct_answer_ranks:
        return None, None

    # Calculate mean
    mean_rank = sum(correct_answer_ranks) / len(correct_answer_ranks)

    # Calculate standard deviation
    if len(correct_answer_ranks) == 1:
        std_rank = 0.0
    else:
        variance = sum((r - mean_rank) ** 2 for r in correct_answer_ranks) / len(correct_answer_ranks)
        std_rank = math.sqrt(variance)

    return mean_rank, std_rank


