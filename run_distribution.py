def process_completed_task(
    completed_task: Task,
    answer_free_gen: bool
) -> Dict:
    """
    Convert a completed task to a sample dictionary.

    Args:
        completed_task: Completed task with response
        answer_free_gen: Whether answer-free generation was used

    Returns:
        Dictionary with sample data including extracted answer

    Examples:
        >>> # Mock a successful task
        >>> from llm_client import Response
        >>> task = Task(index=0, request=None, metadata={'sample_id': 0})
        >>> task.response = Response(
        ...     content="\\\\boxed{42}",
        ...     history="",
        ...     elapsed_seconds=1.0,
        ...     success=True
        ... )
        >>> sample = process_completed_task(task, answer_free_gen=False)
        >>> sample['success']
        True
        >>> sample['extracted_answer']
        '42'
    """
    response = completed_task.response
    sample_id = completed_task.metadata.get('sample_id', completed_task.index)

    if response.success and response.content:
        # Add PREFILL_TEXT prefix when not using answer_free_gen
        if answer_free_gen:
            raw_completion = response.content
        else:
            raw_completion = PREFILL_TEXT + response.content

        extracted_answer = extract_answer_from_completion(raw_completion)

        return {
            'sample_id': sample_id,
            'raw_completion': raw_completion,
            'extracted_answer': extracted_answer,
            'success': True
        }
    else:
        return {
            'sample_id': sample_id,
            'raw_completion': None,
            'extracted_answer': None,
            'success': False,
            'error': response.err_message
        }


